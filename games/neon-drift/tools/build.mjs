import { build } from 'esbuild';
import { mkdir, copyFile, cp } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const out=process.env.NEON_BUILD_OUT?process.env.NEON_BUILD_OUT.replace(/\/?$/,'/'):fileURLToPath(new URL('../../../public/games/neon-drift/',import.meta.url));
await mkdir(out,{recursive:true});
await build({entryPoints:[root+'src/main.js'],bundle:true,format:'esm',target:'es2022',minify:process.env.NEON_DEV_BUILD!=='1',sourcemap:process.env.NEON_DEV_BUILD==='1'?'external':false,outfile:out+'game.js',legalComments:'eof'});
for(const file of ['index.html','style.css']) await copyFile(root+'src/'+file,out+file);
await copyFile(root+'node_modules/three/LICENSE',out+'THREE-LICENSE.txt');
await cp(root+'../../assets/games/neon-drift/generated',out+'assets',{recursive:true});
console.log('Neon Drift runtime built with bundled Three.js 0.170.0');
